test('Ctrl+L opens the go-to-line dialog', async () => {
    const view = await mountEditor(initEditor);

    // The previous (Ace) editor bound go to line to Ctrl+L / Cmd+L.
    const event = pressKey(view.contentDOM, 'l', { ctrl: true });

    expect(event.defaultPrevented).toBe(true);
    expect(view.dom.querySelector('.cm-panel.cm-dialog')).not.toBeNull();
    expect(view.dom.textContent).toContain('Go to line');
    view.destroy();
});

test('Ctrl+D deletes the current line', async () => {
    const view = await mountEditor(initEditor);
    view.dispatch({ changes: { from: 0, insert: '||a.com^\n||b.com^\n||c.com^' } });
    view.dispatch({ selection: { anchor: view.state.doc.line(2).from } });

    // The previous (Ace) editor bound delete line to Ctrl+D / Cmd+D, which
    // supersedes CodeMirror's "select next occurrence" on the same chord.
    const event = pressKey(view.contentDOM, 'd', { ctrl: true });

    expect(event.defaultPrevented).toBe(true);
    expect(view.state.doc.toString()).toBe('||a.com^\n||c.com^');
    view.destroy();
});
