test('Ctrl+Shift+Z redoes the last undone change', async () => {
    const view = await mountEditor(initEditor);

    view.dispatch({ changes: { from: 0, insert: '||example.com^' } });
    expect(undo(view)).toBe(true);
    expect(view.state.doc.toString()).toBe('');

    // Simulate Ctrl+Shift+Z. jsdom's `navigator.platform` is empty, so
    // CM6 resolves keymaps on its generic "key" platform, where `Mod`
    // means Ctrl — reproducing the Windows binding set (the
    // `hotkeys.mode` config does not affect keymap resolution). Real
    // browsers report `key` as uppercase 'Z' while Shift is held; CM6
    // then resolves the binding through `base[event.keyCode]`. jsdom
    // never populates the legacy `keyCode`, so stub it (90 = Z).
    const event = new KeyboardEvent('keydown', {
        key: 'Z',
        ctrlKey: true,
        shiftKey: true,
        bubbles: true,
        cancelable: true,
    });
    Object.defineProperty(event, 'keyCode', { get: () => 90 });
    view.contentDOM.dispatchEvent(event);

    expect(event.defaultPrevented).toBe(true);
    expect(view.state.doc.toString()).toBe('||example.com^');
    view.destroy();
});

test('focuses the editor on initialization so hotkeys work immediately', async () => {
    const view = await mountEditor(initEditor);
    // The editor must be focused as soon as it is created, otherwise
    // CodeMirror keymaps (Ctrl+F/Ctrl+H) ignore keydown events until the
    // user clicks inside the editor.
    expect(view.hasFocus).toBe(true);
    expect(document.activeElement).toBe(view.contentDOM);
    view.destroy();
});

test('does not steal focus when autofocus is disabled', async () => {
    const input = document.createElement('input');
    document.body.appendChild(input);
    input.focus();

    // Pages with several editors (or a focused element elsewhere) opt out
    // so the editor does not steal focus on creation.
    const view = await mountEditor(initEditor, { autofocus: false });

    expect(view.hasFocus).toBe(false);
    expect(document.activeElement).toBe(input);
    view.destroy();
});

test('Ctrl+F opens the search panel at the bottom of the editor', async () => {
    const view = await mountEditor(initEditor);

    const event = pressCtrlKey(view, 'f');

    expect(event.defaultPrevented).toBe(true);
    expect(searchPanelOpen(view.state)).toBe(true);
    expect(view.dom.querySelector('.cm-panel.cm-search')).not.toBeNull();
    // The default search UI is pinned to the bottom of the editor.
    expect(view.dom.querySelector('.cm-panels-bottom')).not.toBeNull();
    expect(view.dom.querySelector('.cm-panels-top')).toBeNull();
    view.destroy();
});

test('allows consumers to configure the search panel via conf.extensions', async () => {
    const view = await mountEditor(initEditor, {
        // Consumers may pass their own search extension (e.g. to pin the
        // panel to the top); the built-in `search()` must not clash with it.
        extensions: [search({ top: true })],
    });

    const event = pressCtrlKey(view, 'f');

    expect(event.defaultPrevented).toBe(true);
    expect(searchPanelOpen(view.state)).toBe(true);
    // The consumer's `top: true` config wins over the editor default.
    expect(view.dom.querySelector('.cm-panels-top')).not.toBeNull();
    expect(view.dom.querySelector('.cm-panels-bottom')).toBeNull();
    view.destroy();
});

test('Ctrl+H opens the search panel with the focus in the replace field', async () => {
    const view = await mountEditor(initEditor);

    const event = pressCtrlKey(view, 'h');

    expect(event.defaultPrevented).toBe(true);
    expect(searchPanelOpen(view.state)).toBe(true);
    const replaceField = view.dom.querySelector(
        '.cm-panel.cm-search input[name="replace"]',
    );
    expect(replaceField).not.toBeNull();
    // Ctrl+H is "find & replace", so the replace field must get the focus
    // (unlike Ctrl+F which focuses the find field).
    expect(document.activeElement).toBe(replaceField);
    view.destroy();
});

test('Ctrl+H falls back to the find field in a read-only editor', async () => {
    // A read-only editor's search panel has no replace field (and neither
    // does a custom consumer panel), so the shortcut must focus the find
    // field instead of swallowing the key with the focus left outside the
    // panel.
    const view = await mountEditor(initEditor, {
        extensions: [EditorState.readOnly.of(true)],
    });

    const event = pressCtrlKey(view, 'h');

    expect(event.defaultPrevented).toBe(true);
    expect(searchPanelOpen(view.state)).toBe(true);
    expect(view.dom.querySelector('.cm-panel.cm-search input[name="replace"]')).toBeNull();
    const findField = view.dom.querySelector('.cm-panel.cm-search input[name="search"]');
    expect(document.activeElement).toBe(findField);
    view.destroy();
});

