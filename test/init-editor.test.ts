test('Ctrl+S triggers onSave while the search panel has focus', async () => {
    const onSave = vi.fn();
    const view = await mountEditor(initEditor, { hotkeys: { onSave } });

    pressCtrlKey(view, 'f');
    const findField = view.dom.querySelector('.cm-panel.cm-search input[name="search"]');
    expect(findField).not.toBeNull();

    // The save binding is scoped to the search panel as well, so Ctrl+S
    // keeps working while the focus is inside the open panel instead of
    // falling through to the browser.
    const event = pressKey(findField!, 's', { ctrl: true });

    expect(event.defaultPrevented).toBe(true);
    expect(onSave).toHaveBeenCalledWith(view);
    view.destroy();
});

test('Ctrl+/ toggles comments while the search panel has focus', async () => {
    const view = await mountEditor(initEditor);
    view.dispatch({ changes: { from: 0, insert: '||example.com^' } });

    pressCtrlKey(view, 'f');
    const findField = view.dom.querySelector('.cm-panel.cm-search input[name="search"]');
    expect(findField).not.toBeNull();

    const event = pressKey(findField!, '/', { ctrl: true });

    expect(event.defaultPrevented).toBe(true);
    expect(view.state.doc.toString()).toBe('! ||example.com^');
    view.destroy();
});

