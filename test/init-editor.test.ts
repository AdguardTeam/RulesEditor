// The README documents the keymap precedence: the AdGuard bindings run at
// `Prec.high` and cannot be shadowed from `conf.extensions` at the same
// precedence, while the stock CodeMirror keymaps run at the default
// precedence and can.
test('a Prec.high binding in conf.extensions shadows the stock search keymap', async () => {
    const consumerFind = vi.fn(() => true);
    const view = await mountEditor(initEditor, {
        // `Mod-f` is bound by `searchKeymap`, which runs at the default
        // precedence, so the consumer's `Prec.high` binding is consulted first.
        extensions: [Prec.high(keymap.of([{ key: 'Mod-f', run: consumerFind }]))],
    });

    const event = pressCtrlKey(view, 'f');

    expect(event.defaultPrevented).toBe(true);
    expect(consumerFind).toHaveBeenCalledWith(view);
    expect(searchPanelOpen(view.state)).toBe(false);
    view.destroy();
});

test('a Prec.high binding in conf.extensions cannot shadow an AdGuard binding', async () => {
    const onSave = vi.fn();
    const consumerSave = vi.fn(() => true);
    const view = await mountEditor(initEditor, {
        hotkeys: { onSave },
        // Both `Mod-s` bindings run at `Prec.high`, and at equal precedence
        // the earlier extension wins — the built-in one is registered first.
        extensions: [Prec.high(keymap.of([{ key: 'Mod-s', run: consumerSave }]))],
    });

    const event = pressCtrlKey(view, 's');

    expect(event.defaultPrevented).toBe(true);
    expect(onSave).toHaveBeenCalledWith(view);
    expect(consumerSave).not.toHaveBeenCalled();
    view.destroy();
});

